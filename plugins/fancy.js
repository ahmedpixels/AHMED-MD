function stylize(text, style) {
    let result = ''
    for (const ch of text) {
        const code = ch.charCodeAt(0)
        if (code >= 65 && code <= 90) {
            const idx = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.indexOf(ch)
            const arr = Array.from(style.upper)
            result += arr[idx] || ch
        } else if (code >= 97 && code <= 122) {
            const idx = 'abcdefghijklmnopqrstuvwxyz'.indexOf(ch)
            const arr = Array.from(style.lower)
            result += arr[idx] || ch
        } else if (code >= 48 && code <= 57) {
            const arr = Array.from(style.digits)
            result += arr[code - 48] || ch
        } else {
            result += ch
        }
    }
    return result
}

